import { motion } from 'framer-motion';
import { FileSpreadsheet } from 'lucide-react';
import { cn } from '@/lib/utils';
import type { SheetModel, CellTone } from './sheets';

const COL = 'ABCDEFGHIJKLMNOP';

const toneClass: Record<CellTone, string> = {
  pos: 'text-emerald-700',
  neg: 'text-red-600',
  flag: 'text-red-700 font-semibold bg-red-50',
  muted: 'text-slate-500',
  link: 'text-blue-600 underline',
};

interface Props {
  sheet: SheetModel;
  revealedRows: number;
  selected?: { r: number; c: number } | null;
}

export function DemoSpreadsheet({ sheet, revealedRows, selected }: Props) {
  const cols = sheet.colWidths.length;
  const sel = selected ? sheet.rows[selected.r]?.cells[selected.c] : undefined;
  const ref = selected ? `${COL[selected.c]}${selected.r + 1}` : 'A1';
  const totalRows = Math.max(sheet.rows.length + 6, 18);

  return (
    <div className="h-full w-full flex flex-col bg-white text-[13px] font-[Calibri,'Segoe_UI',sans-serif]">
      <div className="flex items-center gap-3 px-4 py-2 bg-[#217346] text-white">
        <FileSpreadsheet className="h-4 w-4" />
        <span className="font-semibold">{sheet.fileName}</span>
        <span className="text-white/70 text-xs">Saved to ~/Downloads/MAGK-Excel · generated by MAGK</span>
      </div>
      <div className="flex items-center border-b bg-slate-50 text-slate-700">
        <div className="w-20 px-2 py-1.5 border-r text-center font-mono text-xs">{ref}</div>
        <div className="px-3 py-1.5 border-r italic text-slate-400 font-serif">fx</div>
        <motion.div
          key={ref}
          initial={{ opacity: 0.3 }}
          animate={{ opacity: 1 }}
          className="px-3 py-1.5 font-mono text-[13px] truncate"
        >
          {sel ? sel.f ?? sel.v : ''}
        </motion.div>
      </div>
      <div className="flex-1 overflow-hidden">
        <table className="border-collapse table-fixed">
          <colgroup>
            <col style={{ width: 40 }} />
            {sheet.colWidths.map((w, i) => (
              <col key={i} style={{ width: w }} />
            ))}
            <col style={{ width: 200 }} />
          </colgroup>
          <thead>
            <tr>
              <th className="bg-slate-100 border border-slate-200 h-6" />
              {Array.from({ length: cols + 1 }).map((_, c) => (
                <th
                  key={c}
                  className={cn(
                    'bg-slate-100 border border-slate-200 font-normal text-xs text-slate-500',
                    selected?.c === c && 'bg-emerald-100 text-emerald-800 font-semibold'
                  )}
                >
                  {COL[c]}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {Array.from({ length: totalRows }).map((_, r) => {
              const row = sheet.rows[r];
              const shown = row && r < revealedRows;
              return (
                <tr key={r} className="h-[30px]">
                  <td
                    className={cn(
                      'bg-slate-100 border border-slate-200 text-center text-xs text-slate-500',
                      selected?.r === r && 'bg-emerald-100 text-emerald-800 font-semibold'
                    )}
                  >
                    {r + 1}
                  </td>
                  {Array.from({ length: cols + 1 }).map((_, c) => {
                    const cell = shown ? row.cells[c] : undefined;
                    const isSel = selected?.r === r && selected?.c === c;
                    const spanTitle = shown && (row.kind === 'title' || row.kind === 'note') && c === 0;
                    if (shown && (row.kind === 'title' || row.kind === 'note') && c > 0) return null;
                    return (
                      <td
                        key={c}
                        colSpan={spanTitle ? cols + 1 : undefined}
                        className={cn(
                          'border border-slate-200 px-2 whitespace-nowrap overflow-hidden relative',
                          shown && row.kind === 'header' && c < cols && 'bg-[#1f4e78] text-white font-semibold',
                          shown && row.kind === 'total' && c < cols && 'bg-slate-100 font-bold border-t-2 border-t-slate-500',
                          shown && row.kind === 'title' && 'text-[16px] font-bold text-[#1f4e78]',
                          cell?.bold && 'font-semibold',
                          cell?.tone && toneClass[cell.tone],
                          cell?.align === 'right' && 'text-right tabular-nums',
                          cell?.align === 'center' && 'text-center'
                        )}
                      >
                        {cell && (
                          <motion.span initial={{ opacity: 0, y: 4 }} animate={{ opacity: 1, y: 0 }} transition={{ duration: 0.25 }}>
                            {cell.v}
                          </motion.span>
                        )}
                        {isSel && (
                          <motion.div
                            layoutId="sel"
                            className="absolute inset-0 border-2 border-[#217346] pointer-events-none"
                            transition={{ type: 'spring', stiffness: 400, damping: 35 }}
                          />
                        )}
                      </td>
                    );
                  })}
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>
      <div className="flex items-center gap-0 border-t bg-slate-100 text-xs">
        {sheet.tabs.map((t) => (
          <div
            key={t}
            className={cn(
              'px-4 py-1.5 border-r',
              t === sheet.activeTab ? 'bg-white text-[#217346] font-semibold border-b-2 border-b-[#217346]' : 'text-slate-600'
            )}
          >
            {t}
          </div>
        ))}
      </div>
    </div>
  );
}
